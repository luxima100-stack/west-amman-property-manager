-- عقارات غرب عمان: قاعدة Supabase للنسخة النهائية المبنية على التصميم الأصلي
create extension if not exists pgcrypto;
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 name text not null default '', email text not null default '',
 role text not null check(role in ('owner','admin')),
 permissions text[] not null default array['dashboard','properties','tenants','reports','settings','messages'],
 created_at timestamptz not null default now()
);
create table if not exists public.properties (
 id bigint generated by default as identity primary key,
 client_id text unique,
 code text not null unique,
 name text not null, area text not null, status text not null default 'متاحة',
 floor numeric, area_size numeric, price numeric not null default 0,
 rooms integer not null default 0, baths integer not null default 0, balcony boolean not null default false,
 availability_date date, alert_days integer not null default 7,
 notes text not null default '', video_url text not null default '', images text[] not null default '{}',
 tenant text not null default '', tenant_phone text not null default '', created_at timestamptz not null default now()
);
alter table public.properties add column if not exists client_id text;
alter table public.properties add column if not exists alert_days integer not null default 7;
alter table public.properties add column if not exists tenant text not null default '';
alter table public.properties add column if not exists tenant_phone text not null default '';
update public.properties set client_id=id::text where client_id is null;
create unique index if not exists properties_client_id_uq on public.properties(client_id) where client_id is not null;
create table if not exists public.app_state (
 id text primary key, data jsonb not null default '{}'::jsonb,
 updated_by uuid references auth.users(id) on delete set null, updated_at timestamptz not null default now()
);
create table if not exists public.login_logs (
 id bigint generated by default as identity primary key,
 user_id uuid references auth.users(id) on delete set null,
 email text, success boolean not null default true, created_at timestamptz not null default now()
);
insert into storage.buckets(id,name,public) values('property-images','property-images',true) on conflict(id) do update set public=true;
alter table public.profiles enable row level security;
alter table public.properties enable row level security;
alter table public.app_state enable row level security;
alter table public.login_logs enable row level security;
drop policy if exists "public read properties" on public.properties;
create policy "public read properties" on public.properties for select using(true);
