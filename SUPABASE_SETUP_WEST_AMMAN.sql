create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  email text not null default '',
  role text not null check (role in ('owner','admin')),
  permissions text[] not null default array['dashboard','properties','tenants','reports','settings','messages'],
  created_at timestamptz not null default now()
);

create table if not exists public.properties (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  area text not null,
  status text not null default 'متاحة',
  floor numeric,
  area_size numeric,
  price numeric not null default 0,
  rooms integer not null default 0,
  baths integer not null default 0,
  salon integer not null default 0,
  balcony boolean not null default false,
  availability_date date,
  alert_days integer not null default 7,
  notes text not null default '',
  video_url text not null default '',
  images text[] not null default '{}',
  created_at timestamptz not null default now()
);

create table if not exists public.tenants (
  id bigint generated by default as identity primary key,
  name text not null default '',
  phone text not null default '',
  property_code text not null default '',
  contract_start date,
  contract_end date,
  alert_days integer not null default 7,
  created_at timestamptz not null default now()
);

create table if not exists public.app_state (
  id integer primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  name text not null default '',
  text text not null default '',
  created_at timestamptz not null default now()
);

